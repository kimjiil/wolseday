const ARNG={atk:[[5,9],[10,14],[15,19],[20,25],[26,33],[34,40]],내공:[[2,4],[5,7],[8,11],[12,19],[20,39],[40,60]],안법:[[3,5],[6,9],[10,13],[14,17],[18,23],[24,28]],보법:[[4,8],[9,11],[12,15],[16,19],[20,25],[26,30]],외공:[[1,2],[3,3],[4,5],[6,7],[8,10],[12,14]]};
const arng=k=>ARNG[k]||ARNG.atk, artVal=a=>a.k==='내공'?(a.ng||0):(a.p||0);
function gradeByVal(k,v){ const r=arng(k); let g=0; for(let i=0;i<6;i++) if(v>=r[i][0]) g=i; return g; }
function AR(kind,grade,list,sect){ const ks=kind.split('/'), k=ks[0], g=TIER.indexOf(grade), r=arng(k)[g];
  list.split('|').forEach(row=>{ const p=row.trim().split(':'), n=p[0]; if(!n) return; if(ARTS[n]){ ARTDUP.push(n); return; }
    const fix=p[1]!=null, v=fix?+p[1]:r[0]+strHash(n)%(r[1]-r[0]+1); ARTS[n]={n,k,sub:ks[1]||null,g:fix?gradeByVal(k,v):g,p:k==='내공'?0:v,ng:k==='내공'?v:0,sect:sect||null}; }); }
function SA(sect,list){ list.split('|').forEach(row=>{ const x=/^(\S+?)(SSR|SS|S|A|B|C)\s+(.+)$/.exec(row.trim()); if(x) AR(x[1],x[2],x[3],sect); }); }
