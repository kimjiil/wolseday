const artStat=a=>a.k==='내공'?`내공 +${Math.round((a.ng||0)*10)/10}년`:a.k==='안법'?`낌새 읽기 +${a.p}%`:a.k==='보법'?`회피 +${Math.round(stepEv(a.p)*100)}%`:a.k==='외공'?`방어 +${a.p}`:`위력 ${a.p}`;
const knows=n=>m.arts.some(a=>a.n===n);
function learnArt(n,ngMul){ const A=ARTS[n]; if(!A) return false; return learn(A.n,A.p,A.k,A.k==='내공'?Math.max(1,Math.round(A.ng*(ngMul==null?1:ngMul))):A.ng); }

